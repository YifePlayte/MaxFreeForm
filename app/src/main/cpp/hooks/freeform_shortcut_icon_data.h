constexpr size_t kOriginalSize = 662u;
constexpr uint64_t kOriginalFnv1a64 = 0x0056c920f9c7b50aULL;

// Nothing security-relevant depends on this digest: a hit only selects which
// bytes to hand to libwebp. The length check plus a well-spread 64-bit hash
// makes an accidental collision irrelevant, and the whole image is decoded
// afterwards by the launcher's own decoder.
inline bool MatchesOriginal(const void* buffer, size_t length) {
    if (buffer == nullptr || length != kOriginalSize) return false;
    const auto* bytes = static_cast<const uint8_t*>(buffer);
    uint64_t hash = 0xcbf29ce484222325ULL;
    for (size_t index = 0u; index < length; ++index) {
        hash = (hash ^ bytes[index]) * 0x100000001b3ULL;
    }
    return hash == kOriginalFnv1a64;
}

